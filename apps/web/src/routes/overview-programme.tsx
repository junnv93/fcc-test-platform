import { ConsoleHome } from './console-home';

/**
 * `/programme` — 시험 진행 현황.
 *
 * ┌─ 목적 ────────────────────────────────────────────────────────────────┐
 * │ 누가   PM 팀                                                           │
 * │ 언제   주간 점검, 그리고 «고객사 보고서를 만들 때»                     │
 * │ 무엇에 답하나                                                          │
 * │        · 이 모델이 전체 계획 대비 어디까지 왔나                        │
 * │        · 어느 대분류/계열/모드가 늦나                                  │
 * │        · 남은 것이 시간으로 얼마나 되나                                │
 * │ 답하지 않는 것   무엇을 지금 측정할지 (그것은 `/` 이다)                │
 * └──────────────────────────────────────────────────────────────────────┘
 *
 * ⚠️ 이 화면의 산출물은 «보고»다. 그래서 모델 토글이 있고(보고는 항상 한 모델에
 * 대한 것이다), 그래서 내보내기가 있다. 내보내기가 무엇을 만들지는 아직 PM 팀과
 * 정하지 않았고, 그 미정 상태를 버튼이 스스로 말한다 — `routes.home.export*`.
 *
 * ⚠️ 「전체 모델 합산」 보기는 «없다». 848U 가 90% 이고 840 이 10% 일 때
 * 「50%」인 시험은 존재하지 않고, 그 숫자로는 고객사에 아무 말도 할 수 없다.
 */
export function ProgrammeOverviewRoute(): JSX.Element {
  return <ConsoleHome scope="pm" />;
}

export default ProgrammeOverviewRoute;
