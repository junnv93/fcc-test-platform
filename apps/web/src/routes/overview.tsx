import { ConsoleHome } from './console-home';

/**
 * `/` — 시험 현장.
 *
 * ┌─ 목적 ────────────────────────────────────────────────────────────────┐
 * │ 누가   시험원 (측정을 직접 도는 사람)                                  │
 * │ 언제   출근해서 처음, 그리고 측정 사이사이                             │
 * │ 무엇에 답하나                                                          │
 * │        · 내 프로젝트에서 «무엇이» 남았나                               │
 * │        · 그 항목이 지난번에 어떻게 판정됐나                            │
 * │        · 지금 쓸 수 있는 시험 구성이 있나                              │
 * │ 답하지 않는 것   일정·원가·고객사 보고 (그것은 `/programme` 이다)      │
 * └──────────────────────────────────────────────────────────────────────┘
 *
 * ⚠️ 이 화면은 «보는 곳»이지 «하는 곳»이 아니다. 측정을 시작·중지하거나 값을
 * 고치는 동작은 여기 두지 않는다 — 벽에 띄워 두는 화면에서 한 번의 오클릭이
 * 되돌릴 수 없는 일을 하면 안 되기 때문이다.
 *
 * 세 홈이 한 컴포넌트를 공유하는 이유 → `console-home.tsx`
 */
export function OverviewRoute(): JSX.Element {
  return <ConsoleHome scope="operator" />;
}

export default OverviewRoute;
